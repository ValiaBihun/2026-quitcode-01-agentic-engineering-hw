import { SIZE, type Board, type Difficulty, type generatePuzzle } from "./sudoku";
import type { Notes, Phase, SavedGame } from "./storage";

// All game-state transitions live here, outside the component, so they can be
// unit-tested without React (see tests/gameReducer.test.ts). The reducer must
// stay pure: anything random or time-based (puzzle generation, wall-clock
// deltas) is computed by the caller and passed in the action.

export type GameState = {
  difficulty: Difficulty;
  solution: Board | null;
  givensMask: boolean[][] | null;
  values: Board | null;
  notes: Notes | null;
  elapsedMs: number;
  phase: Phase;
};

export type GameAction =
  | {
      type: "NEW_GAME";
      difficulty: Difficulty;
      // Generated by the caller: generatePuzzle uses Math.random, so calling
      // it inside the reducer would make the reducer impure (StrictMode
      // double-invokes reducers and would produce two different puzzles).
      generated: ReturnType<typeof generatePuzzle>;
    }
  | { type: "RESTORE"; game: SavedGame }
  | { type: "START" }
  | { type: "TOGGLE_PAUSE" }
  | { type: "TICK"; deltaMs: number }
  | {
      type: "INPUT_DIGIT";
      row: number;
      col: number;
      digit: number;
      mode: "value" | "note";
    }
  | { type: "CLEAR_CELL"; row: number; col: number }
  | { type: "REVEAL_CELL"; row: number; col: number };

export function createEmptyNotes(): Notes {
  return Array.from({ length: SIZE }, () =>
    Array.from({ length: SIZE }, () => [] as number[]),
  );
}

function cloneValues(values: Board): Board {
  return values.map((row) => [...row]);
}

function cloneNotes(notes: Notes): Notes {
  return notes.map((row) => row.map((cell) => [...cell]));
}

export function gameReducer(state: GameState, action: GameAction): GameState {
  switch (action.type) {
    case "NEW_GAME": {
      const { solution, puzzle, givensMask } = action.generated;
      return {
        difficulty: action.difficulty,
        solution,
        givensMask,
        values: puzzle,
        notes: createEmptyNotes(),
        elapsedMs: 0,
        phase: "idle",
      };
    }
    case "RESTORE":
      return { ...action.game };
    case "START":
      return state.phase === "idle" ? { ...state, phase: "playing" } : state;
    case "TOGGLE_PAUSE": {
      if (state.phase === "playing") return { ...state, phase: "paused" };
      if (state.phase === "paused") return { ...state, phase: "playing" };
      return state;
    }
    case "TICK":
      return { ...state, elapsedMs: state.elapsedMs + action.deltaMs };
    case "INPUT_DIGIT": {
      if (!state.values || !state.givensMask || !state.notes) return state;
      if (state.givensMask[action.row][action.col]) return state;

      if (action.mode === "value") {
        const values = cloneValues(state.values);
        values[action.row][action.col] = action.digit;
        const notes = cloneNotes(state.notes);
        notes[action.row][action.col] = [];
        return { ...state, values, notes };
      }

      // Notes mode: pencil marks only make sense on a cell with no final
      // value yet.
      if (state.values[action.row][action.col] !== 0) return state;
      const notes = cloneNotes(state.notes);
      const cellNotes = notes[action.row][action.col];
      const existingIndex = cellNotes.indexOf(action.digit);
      if (existingIndex >= 0) {
        cellNotes.splice(existingIndex, 1);
      } else {
        cellNotes.push(action.digit);
        cellNotes.sort((a, b) => a - b);
      }
      return { ...state, notes };
    }
    case "CLEAR_CELL": {
      if (!state.values || !state.givensMask || !state.notes) return state;
      if (state.givensMask[action.row][action.col]) return state;
      const values = cloneValues(state.values);
      values[action.row][action.col] = 0;
      const notes = cloneNotes(state.notes);
      notes[action.row][action.col] = [];
      return { ...state, values, notes };
    }
    case "REVEAL_CELL": {
      if (!state.values || !state.givensMask || !state.notes || !state.solution) {
        return state;
      }
      if (state.givensMask[action.row][action.col]) return state;
      if (state.values[action.row][action.col] !== 0) return state;
      const values = cloneValues(state.values);
      values[action.row][action.col] = state.solution[action.row][action.col];
      const notes = cloneNotes(state.notes);
      notes[action.row][action.col] = [];
      return { ...state, values, notes };
    }
    default:
      return state;
  }
}

export const INITIAL_GAME_STATE: GameState = {
  difficulty: "medium",
  solution: null,
  givensMask: null,
  values: null,
  notes: null,
  elapsedMs: 0,
  phase: "idle",
};

// Major #2 from the 08.09 review: changing difficulty or pressing New Game
// mid-puzzle silently discarded the game. A started, unfinished game is
// "something to lose" and must go through the confirmation modal; an idle
// board or a won game can be replaced right away.
export function needsNewGameConfirmation(phase: Phase, isWon: boolean): boolean {
  return (phase === "playing" || phase === "paused") && !isWon;
}
